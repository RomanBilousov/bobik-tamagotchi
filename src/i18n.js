function hasWindow() {
  return typeof window !== 'undefined';
}

function readStoredLang() {
  if (!hasWindow()) {
    return null;
  }

  return window.localStorage.getItem('bobik_lang');
}

function writeStoredLang(lang) {
  if (!hasWindow()) {
    return;
  }

  window.localStorage.setItem('bobik_lang', lang);
}

export function getLang() {
  if (!hasWindow()) {
    return 'en';
  }

  const urlParams = new URLSearchParams(window.location.search);
  const urlLang = urlParams.get('lang');
  
  if (urlLang && dictionary[urlLang]) {
    writeStoredLang(urlLang);
    return urlLang;
  }
  
  const match = window.location.pathname.match(/^\/(en|ua|ru)(\/|$)/i);
  if (match && dictionary[match[1].toLowerCase()]) {
    writeStoredLang(match[1].toLowerCase());
    return match[1].toLowerCase();
  }
  
  const saved = readStoredLang();
  if (saved && dictionary[saved]) return saved;
  
  return 'en';
}

export function t(key) {
  const lang = getLang();
  const translations = dictionary[lang] || dictionary['en'];
  return translations[key] || dictionary['en'][key] || key;
}

export function getNextLang(current = getLang()) {
  const langs = Object.keys(dictionary);
  return langs[(langs.indexOf(current) + 1) % langs.length];
}

export function setLang(nextLang) {
  if (!dictionary[nextLang]) {
    return getLang();
  }

  if (!hasWindow()) {
    return nextLang;
  }

  writeStoredLang(nextLang);

  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.has('lang')) {
    urlParams.set('lang', nextLang);
    window.history.replaceState({}, '', `${window.location.pathname}?${urlParams.toString()}`);
  }

  return nextLang;
}

export function cycleLang() {
  const nextLang = getNextLang();
  setLang(nextLang);
  if (hasWindow()) {
    window.location.reload();
  }
  return nextLang;
}
